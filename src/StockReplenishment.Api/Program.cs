using Microsoft.EntityFrameworkCore;
using StockReplenishment.Api.Application;
using StockReplenishment.Api.Data;
using StockReplenishment.Api.Infrastructure;
using StockReplenishment.Api.StockChecks;
using StockReplenishment.Contracts.Common;

var builder = WebApplication.CreateBuilder(args);

// Persistence: SQLite in-memory (relational, enforces FKs and concurrency tokens, no installation needed).
builder.Services.AddSingleton(sp =>
    new InMemoryDatabase(sp.GetRequiredService<IConfiguration>()["Database:Name"] ?? "StockReplenishment"));
builder.Services.AddDbContext<AppDbContext>((sp, options) => options
    .UseSqlite(sp.GetRequiredService<InMemoryDatabase>().ConnectionString)
    .AddInterceptors(new SharedCacheConnectionInterceptor()));

// Application
builder.Services.AddSingleton(TimeProvider.System);
builder.Services.AddHttpContextAccessor();
builder.Services.AddScoped<ICurrentUser, HttpCurrentUser>();
builder.Services.AddScoped<IReplenishmentRequestService, ReplenishmentRequestService>();
builder.Services.AddScoped<ICatalogService, CatalogService>();
builder.Services.AddSingleton<IRequestNotifier, SignalRRequestNotifier>();

// Background stock availability checks
builder.Services.AddOptions<StockCheckOptions>()
    .BindConfiguration(StockCheckOptions.SectionName)
    .ValidateDataAnnotations()
    .ValidateOnStart();
builder.Services.AddOptions<SimulatedStockServiceOptions>()
    .BindConfiguration(SimulatedStockServiceOptions.SectionName)
    .Validate(o => o.MinLatency <= o.MaxLatency, "MinLatency must not exceed MaxLatency.")
    .ValidateDataAnnotations()
    .ValidateOnStart();
builder.Services.AddSingleton<IStockAvailabilityService, SimulatedStockAvailabilityService>();
builder.Services.AddSingleton<IStockCheckQueue, StockCheckQueue>();
builder.Services.AddScoped<StockCheckProcessor>();
builder.Services.AddHostedService<StockCheckWorker>();

// Web
builder.Services.AddControllers();
builder.Services.AddProblemDetails();
builder.Services.AddExceptionHandler<ApiExceptionHandler>();
builder.Services.AddSignalR();
builder.Services.AddOpenApi(options =>
{
    options.AddDocumentTransformer((document, _, _) =>
    {
        document.Info.Title = "Stock Replenishment API";
        document.Info.Description =
            "Replenishment request workflow: Draft → Submitted → Approved → Fulfilled (or Rejected). " +
            "Set the X-User-Name header to choose who you act as; a request cannot be reviewed by its requester.";
        return Task.CompletedTask;
    });
    options.AddOperationTransformer<UserHeaderOperationTransformer>();
});

var app = builder.Build();

await using (var scope = app.Services.CreateAsyncScope())
{
    var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
    await db.Database.EnsureCreatedAsync();
    if (app.Configuration.GetValue("Database:SeedDemoData", true))
    {
        await DemoDataSeeder.SeedAsync(db, scope.ServiceProvider.GetRequiredService<TimeProvider>());
    }
}

app.UseExceptionHandler();
app.UseStatusCodePages();

if (app.Environment.IsDevelopment())
{
    app.MapOpenApi();

    // Interactive API explorer at /swagger, rendering the document generated by MapOpenApi.
    app.UseSwaggerUI(options =>
    {
        options.SwaggerEndpoint("/openapi/v1.json", "Stock Replenishment API v1");
        options.DocumentTitle = "Stock Replenishment API";
    });
    app.UseWebAssemblyDebugging();
}

// Serves the referenced Blazor WebAssembly client (including its _framework files), so a single
// "dotnet run" starts the whole application.
app.MapStaticAssets();

app.MapControllers();
app.MapHub<RequestsHub>(ApiConventions.RequestsHubPath);

// Client-side routes (e.g. /requests/5) get index.html. API paths are excluded, so an unknown API URL
// is a 404 and a known URL with the wrong verb is a 405, instead of an HTML page with status 200.
app.MapFallbackToFile("/", "index.html");
app.MapFallbackToFile("{*path:nonfile:regex(^(?!api/|hubs/|swagger|openapi/).*$)}", "index.html");

app.Run();

/// <summary>Exposed for WebApplicationFactory-based integration tests.</summary>
public partial class Program;
